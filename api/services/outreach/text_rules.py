def check_reply_risks(text: str) -> list[str]:
    """标记短回复中的高风险措辞，沿用已有风险规则，仍需人工复核。"""
    issues = []
    for code, pattern, severity, suggestion in _RISK_PATTERNS:
        if severity == "high":
            for match in list(re.finditer(pattern, text or ""))[:2]:
                issues.append(f"{code}：{match.group(0)}；{suggestion}")
    return issues
