def tail_sentence(text: str) -> str:
    """取末句：先去尾部标点，再按句读切取最后一段。"""
    t = (text or "").strip().rstrip("。！!？?～~\n ")
    if not t:
        return ""
    parts = re.split(r"[。！!？?]", t)
    tail = parts[-1] if parts[-1] else (parts[-2] if len(parts) > 1 else t)
    return tail.strip()


